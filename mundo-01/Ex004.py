N = input('Diga algo: ')
print('O tipo do primitivo desse valor e', type(N))
print('So tem espaco?', N.isspace())
print('E um numero?', N.isnumeric())
print('E alfabetico?', N.isalpha())
print('E alfanumerico?', N.isalnum())
print('Esta em maiusculas?', N.isupper())
print('Esta em minuscula?', N.islower())
print('Esta capitalizada', N.istitle())



